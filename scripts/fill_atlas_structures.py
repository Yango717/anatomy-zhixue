COMMON = frozenset({'的','与','和','及','或','中','前','后','左','右','图','图谱','模式','概览','系统','结构','形态','位置','分部','本章','数字','资源','全貌','后面观','前面观','右侧面','矢状','水平','切面','全貌','示意图','观','面','侧','示','男','女'})


def get_structures(title):
    results = []
    title_norm = title.replace('（','(').replace('）',')')

    # 1. 精确/部分匹配结构库
    for key, structs in STRUCTURE_MAP.items():
        if key in title_norm:
            results.extend(structs)

    # 2. 从标题中提取有意义的词作为补充结构
    clean = re.sub(r'[（(][^)）]*[)）]', '', title_norm)
    parts = re.split(r'[、，,·\s（）()]+', clean)
    extra = []
    for p in parts:
        p = p.strip()
        if len(p) >= 2 and p not in COMMON and not p.endswith('图') and not p.endswith('面'):
            extra.append((p, ''))
    results = extra + results  # 标题词放前面

    # 去重（按label）
    seen = set()
    unique = []
    for item in results:
        label = item[0] if isinstance(item, tuple) else item['label']
        if label not in seen:
            seen.add(label)
            if isinstance(item, tuple):
                unique.append({'label': item[0], 'desc': item[1]})
            else:
                unique.append(item)
    return unique[:12]


